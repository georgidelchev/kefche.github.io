-- Word of the Day, the game (Phase 13 step 21, SPEC §20.7 #62, Q5): guess
-- the day's five-letter word in six tries, in English and Bulgarian.
--
-- - The day's word is public.words_of_the_day's (Phase 7), which anyone
--   reads from its day on. This adds a year of words for both languages,
--   from each one's answers (packages/games/word-of-the-day/content), in a
--   fixed shuffle. An admin can still replace a coming day's
--   (staff_set_word), which now insists on five letters in these two.
-- - A daily streak per player, game and language (daily_streaks; Mini
--   Crossword's daily will use it too): days in a row solved, the games
--   played and won, and how many tries the wins took. finish_daily_word
--   records today's game once; daily_streak reads it.
-- - The word reaches the browser at the start, as in every such game, so
--   these results are the player's word, and Word of the Day has no board.

create table public.daily_streaks (
  user_id uuid not null references auth.users (id) on delete cascade,
  game_id text not null check (game_id ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and length(game_id) <= 40),
  locale public.locale_code not null,
  current integer not null default 0 check (current >= 0),
  best integer not null default 0 check (best >= 0),
  played integer not null default 0 check (played >= 0),
  won integer not null default 0 check (won >= 0),
  -- Wins by tries: spread[1] in one, … spread[6] in six.
  spread integer[] not null default '{0,0,0,0,0,0}' check (cardinality(spread) = 6),
  last_day date,
  last_won date,
  primary key (user_id, game_id, locale)
);
alter table public.daily_streaks enable row level security;
create policy "owners read their daily streaks" on public.daily_streaks
  for select to authenticated
  using (user_id = (select auth.uid()));
revoke all on public.daily_streaks from anon, authenticated;
grant select on public.daily_streaks to authenticated;

-- A streak as the browser shows it: one not carried on yesterday or today
-- has ended.
create function private.daily_streak_json(p_row public.daily_streaks)
returns jsonb
language sql
stable
set search_path = ''
as $$
  select jsonb_build_object(
    'current', case
      when p_row.last_won >= (now() at time zone 'utc')::date - 1 then p_row.current
      else 0 end,
    'best', p_row.best,
    'played', p_row.played,
    'won', p_row.won,
    'spread', to_jsonb(p_row.spread),
    'lastDay', p_row.last_day
  );
$$;

-- The signed-in player's streak in a daily game and language, or null
-- before their first. Error: not_signed_in.
create function public.daily_streak(p_game text, p_locale text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
  v_row public.daily_streaks;
begin
  if v_user is null then
    raise exception 'not_signed_in' using errcode = 'insufficient_privilege';
  end if;
  select * into v_row from public.daily_streaks s
  where s.user_id = v_user and s.game_id = p_game and s.locale::text = p_locale;
  if not found then
    return null;
  end if;
  return private.daily_streak_json(v_row);
end;
$$;

-- Records the signed-in player's Word of the Day for today (UTC) in a
-- language, from their guesses (folded, as the game compares them): solved
-- by the last of up to six, or six misses. Only the first game of a day
-- counts; a second returns the streak unchanged. Returns the streak.
-- Errors: not_signed_in, no_word, invalid_guesses.
create function public.finish_daily_word(p_locale text, p_guesses text[])
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
  v_today date := (now() at time zone 'utc')::date;
  v_n integer := coalesce(cardinality(p_guesses), 0);
  v_word text;
  v_won boolean;
  v_carried boolean;
  v_row public.daily_streaks;
begin
  if v_user is null then
    raise exception 'not_signed_in' using errcode = 'insufficient_privilege';
  end if;
  select w.word into v_word from public.words_of_the_day w
  where w.locale::text = p_locale and w.day = v_today;
  if v_word is null then
    raise exception 'no_word' using errcode = 'no_data_found';
  end if;
  if v_n < 1 or v_n > 6
    or exists (select 1 from unnest(p_guesses) g where g is null or char_length(g) <> 5)
    or v_word = any (p_guesses[1:v_n - 1])
    or (p_guesses[v_n] <> v_word and v_n < 6)
  then
    raise exception 'invalid_guesses' using errcode = 'invalid_parameter_value';
  end if;
  v_won := p_guesses[v_n] = v_word;

  insert into public.daily_streaks (user_id, game_id, locale)
  values (v_user, 'word-of-the-day', p_locale::public.locale_code)
  on conflict (user_id, game_id, locale) do nothing;
  select * into v_row from public.daily_streaks s
  where s.user_id = v_user and s.game_id = 'word-of-the-day' and s.locale::text = p_locale
  for update;
  if v_row.last_day is not distinct from v_today then
    return private.daily_streak_json(v_row);
  end if;

  v_carried := v_row.last_won = v_today - 1;
  update public.daily_streaks s set
    played = s.played + 1,
    won = s.won + case when v_won then 1 else 0 end,
    spread = case when v_won
      then s.spread[1:v_n - 1] || (s.spread[v_n] + 1) || s.spread[v_n + 1:6]
      else s.spread end,
    current = case when not v_won then 0 when v_carried then s.current + 1 else 1 end,
    best = greatest(s.best, case when not v_won then 0 when v_carried then s.current + 1 else 1 end),
    last_day = v_today,
    last_won = case when v_won then v_today else s.last_won end
  where s.user_id = v_user and s.game_id = 'word-of-the-day' and s.locale::text = p_locale
  returning * into v_row;
  return private.daily_streak_json(v_row);
end;
$$;

-- In English and Bulgarian the day's word is the game's answer: five
-- letters of the language, stored in lower case. Otherwise as before
-- (20261109100700_content.sql). Errors: admin_only, invalid_word.
create or replace function public.staff_set_word(
  p_locale text,
  p_day date,
  p_word text default null,
  p_meaning text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_word text := nullif(btrim(p_word), '');
  v_meaning text := nullif(btrim(p_meaning), '');
  -- Any character that isn't one of the language's letters: Bulgarian's
  -- are а to ъ, ь, ю and я.
  v_other text := case p_locale
    when 'en' then '[^a-z]'
    else '[^а-ъьюя]' end;
begin
  perform private.require_admin();
  if p_locale in ('en', 'bg') and v_word is not null then
    v_word := lower(v_word);
    if char_length(v_word) <> 5 or v_word ~ v_other then
      raise exception 'invalid_word' using errcode = 'invalid_parameter_value';
    end if;
  end if;
  if p_locale is null or p_locale not in ('en', 'es', 'pt', 'fr', 'de', 'ru', 'zh', 'hi', 'ar', 'ja', 'bg')
    or p_day is null or p_day < (now() at time zone 'utc')::date
    or char_length(v_word) > 40 or char_length(v_meaning) > 300
  then
    raise exception 'invalid_word' using errcode = 'invalid_parameter_value';
  end if;
  if v_word is null then
    delete from public.words_of_the_day where locale::text = p_locale and day = p_day;
    perform private.audit('word.clear', 'word', p_locale || ':' || p_day::text, '{}'::jsonb);
    return;
  end if;
  insert into public.words_of_the_day (locale, day, word, meaning)
  values (p_locale::public.locale_code, p_day, v_word, v_meaning)
  on conflict (locale, day) do update set word = excluded.word, meaning = excluded.meaning;
  perform private.audit('word.set', 'word', p_locale || ':' || p_day::text,
                        jsonb_build_object('word', v_word));
end;
$$;

