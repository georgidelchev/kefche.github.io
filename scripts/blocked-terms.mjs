// Blocked-terms migration generator: `pnpm db:terms`.
// Reads supabase/blocked-terms/*.txt and writes a new migration that replaces
// private.blocked_terms and private.allowed_terms. Match modes and sources are
// documented in supabase/blocked-terms/README.md. Never edit an applied
// migration: change the lists and run this again.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const termsDir = join(root, "supabase/blocked-terms");
const migrationsDir = join(root, "supabase/migrations");

const CJK = /[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}]/u;
const NON_WORD = /[^\p{L}\p{N}]+/gu;

/** Non-empty, non-comment lines. */
const readList = (file) =>
  readFileSync(join(termsDir, file), "utf8")
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line !== "" && !line.startsWith("#"));

function matchMode(lang, term) {
  if (CJK.test(term)) return "contains";
  if (/\s/.test(term)) return "contains"; // phrase, matched with spaces removed
  if (lang === "en" && term.replace(NON_WORD, "").length >= 4) return "contains";
  return "token";
}

const sqlString = (s) => `'${s.replaceAll("'", "''")}'`;

const langs = readdirSync(termsDir)
  .filter((f) => f.endsWith(".txt") && f !== "allowed.txt")
  .map((f) => f.slice(0, -".txt".length))
  // English first: on duplicates across lists, the first entry wins.
  .sort((a, b) => (a === "en" ? -1 : b === "en" ? 1 : a.localeCompare(b)));

const rows = [];
for (const lang of langs) {
  for (const term of readList(`${lang}.txt`)) {
    // Bare digits normalize into letters ("13" → "ie") and would block innocent text.
    if (/^[\p{N}\s\p{P}]*$/u.test(term)) continue;
    rows.push(
      `  (${String(rows.length + 1)}, ${sqlString(term)}, ${sqlString(lang)}, ${sqlString(matchMode(lang, term))})`,
    );
  }
}
const allowed = readList("allowed.txt").map((term) => `  (${sqlString(term)})`);

// Timestamped after the newest existing migration, so order is preserved even
// when local clocks disagree.
const pad = (n) => String(n).padStart(2, "0");
const toStamp = (d) =>
  `${String(d.getUTCFullYear())}${pad(d.getUTCMonth() + 1)}${pad(d.getUTCDate())}` +
  `${pad(d.getUTCHours())}${pad(d.getUTCMinutes())}${pad(d.getUTCSeconds())}`;
const latest = readdirSync(migrationsDir)
  .map((f) => /^(\d{14})_/.exec(f)?.[1])
  .filter(Boolean)
  .sort()
  .at(-1);
let stamp = toStamp(new Date());
if (latest && stamp <= latest) {
  const [, y, mo, d, h, mi, s] = /^(\d{4})(\d{2})(\d{2})(\d{2})(\d{2})(\d{2})$/.exec(latest);
  stamp = toStamp(new Date(Date.UTC(+y, +mo - 1, +d, +h, +mi, +s + 1)));
}

const sql = `-- Generated by scripts/blocked-terms.mjs from supabase/blocked-terms/.
-- Do not edit; change the lists and run \`pnpm db:terms\` to add a new migration.
-- Sources and license (CC BY 4.0 attribution): supabase/blocked-terms/README.md.

delete from private.blocked_terms;
delete from private.allowed_terms;

-- Terms are normalized like the text they're matched against (separators
-- removed, then private.normalize_term). Duplicates keep the first entry.
insert into private.blocked_terms (term, lang, match)
select distinct on (normalized) normalized, lang, match
from (
  select private.normalize_term(regexp_replace(raw, '[^[:alnum:]]+', '', 'g')) as normalized,
         lang, match, ord
  from (values
${rows.join(",\n")}
  ) as t(ord, raw, lang, match)
) s
where char_length(normalized) >= 2
order by normalized, ord;

insert into private.allowed_terms (term)
select distinct private.normalize_term(raw)
from (values
${allowed.join(",\n")}
) as t(raw);
`;

const file = join(migrationsDir, `${stamp}_blocked_terms.sql`);
writeFileSync(file, sql);
console.log(
  `Wrote ${relative(root, file).replaceAll("\\", "/")}: ${String(rows.length)} terms in ${String(langs.length)} lists, ${String(allowed.length)} allowed words.`,
);
