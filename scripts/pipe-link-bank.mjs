// Pipe Link's puzzle bank: `node scripts/pipe-link-bank.mjs` writes
// packages/games/pipe-link/engine/bank.gen.ts. Each puzzle comes from
// engine/generate.ts and is kept only if its solver finds exactly one
// solution, which can take seconds at 8 × 8 and 9 × 9, too slow to do while
// someone waits (or for the server's replay). The bank is committed; the
// engine turns, flips and recolours its puzzles from the seed.
//
// `--sizes=5,6` and `--count=N` limit a run; existing sizes are kept.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
const option = (name, fallback) =>
  process.argv.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3) ?? fallback;
const COUNTS = { 5: 60, 6: 60, 7: 50, 8: 30, 9: 20 };
const sizes = option("sizes", "5,6,7,8,9").split(",").map(Number);
const out = join(root, "packages/games/pipe-link/engine/bank.gen.ts");

const bundle = await build({
  entryPoints: [join(root, "packages/games/pipe-link/engine/generate.ts")],
  bundle: true,
  format: "esm",
  platform: "neutral",
  write: false,
  logLevel: "warning",
});
const tmp = join(root, "node_modules/.pipe-link-generate.mjs");
writeFileSync(tmp, bundle.outputFiles[0]?.text ?? "");
const { makePuzzle, countSolutions } = await import(
  `${pathToFileURL(tmp).href}?t=${String(Date.now())}`
);

// Keep what's there for sizes not being made now.
const bank = {};
if (existsSync(out)) {
  const text = readFileSync(out, "utf8");
  const json = text.slice(text.indexOf("{"), text.lastIndexOf("}") + 1);
  Object.assign(bank, JSON.parse(json.replace(/(\d+):/g, '"$1":').replace(/,\s*}$/, "}")));
}
for (const size of sizes) {
  const count = Number(option("count", String(COUNTS[size] ?? 20)));
  const list = [];
  for (let i = 0; list.length < count && i < count * 6; i++) {
    const started = Date.now();
    const p = makePuzzle(`bank-${String(size)}-${String(i)}`, size);
    if (countSolutions(size, p.ends, 400_000) !== 1) continue;
    list.push(p.ends);
    console.log(
      `${String(size)} × ${String(size)}: ${String(list.length)}/${String(count)} (${String(Date.now() - started)} ms)`,
    );
  }
  bank[size] = list;
}
const body = Object.entries(bank)
  .map(([size, list]) => `  ${size}: ${JSON.stringify(list)},`)
  .join("\n");
writeFileSync(
  out,
  `// Generated by scripts/pipe-link-bank.mjs: do not edit. Each puzzle is its\n// pairs of dots, by colour; every one has exactly one solution.\nexport const BANK: Readonly<Record<number, readonly (readonly (readonly [number, number])[])[]>> = {\n${body}\n};\n`,
);
console.log(
  `bank.gen.ts: ${Object.entries(bank)
    .map(([s, l]) => `${s}: ${String(l.length)}`)
    .join(", ")}`,
);
