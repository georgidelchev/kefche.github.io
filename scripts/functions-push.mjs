// Push words: `pnpm functions:push` (Phase 8 step 12). The send-push Edge
// Function words each notification in its player's language exactly as the
// notifications page does, so this bundles the page's own wording
// (apps/web/src/features/notifications/notification-text.ts) with what it
// needs per locale: the notification strings, game and achievement names,
// and the site's paths, read from the same locale files the site builds
// from. Output: supabase/functions/_shared/push-words.gen.js (typed in
// push-words.gen.d.ts). CI rebuilds it and fails on any difference, so run
// this after changing the notification strings, a game's name or an
// achievement's name.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
const web = join(root, "apps/web");
const { IntlMessageFormat } = createRequire(join(web, "package.json"))("intl-messageformat");
const out = join(root, "supabase/functions/_shared");
const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));

const locales = readdirSync(join(web, "locales"), { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();
// Game folders without a manifest yet are games being built.
const games = readdirSync(join(root, "packages/games"), { withFileTypes: true })
  .filter(
    (entry) =>
      entry.isDirectory() && existsSync(join(root, "packages/games", entry.name, "manifest.ts")),
  )
  .map((entry) => entry.name)
  .sort();

/** A message as `t(key, values)` gives it, with each placeholder left as "{name}" for `fill`. */
const format = (message, locale, placeholders = []) =>
  String(
    new IntlMessageFormat(message, locale).format(
      Object.fromEntries(placeholders.map((p) => [p, `{${p}}`])),
    ),
  );

// The achievements that aren't a game's, by id (profile/achievements.ts's globalText).
const GLOBAL_ACHIEVEMENTS = {
  regular: "regular",
  explorer: "explorer",
  "rising-star": "risingStar",
};

const words = {};
for (const locale of locales) {
  const ns = (name) => readJson(join(web, "locales", locale, `${name}.json`));
  const n = ns("notifications");
  const profile = ns("profile");
  const pools = ns("lobby").rated.pools;
  const plain = (record) =>
    Object.fromEntries(Object.entries(record).map(([key, value]) => [key, format(value, locale)]));
  const placeholders = (message) => [...message.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
  const templates = (record) =>
    Object.fromEntries(
      Object.entries(record).map(([key, value]) => [
        key,
        format(value, locale, placeholders(value)),
      ]),
    );

  const gameNames = {};
  const achievements = {};
  for (const [id, key] of Object.entries(GLOBAL_ACHIEVEMENTS)) {
    achievements[`global.${id}`] = profile.achievements[key].name;
  }
  for (const game of games) {
    const text = readJson(join(root, "packages/games", game, "i18n", `${locale}.json`));
    gameNames[game] = text.name;
    for (const [id, achievement] of Object.entries(text.achievements ?? {})) {
      achievements[`${game}.${id}`] = achievement.name;
    }
  }
  const path = (section) => `/${locale}/${section}`;
  words[locale] = {
    strings: {
      someone: format(n.someone, locale),
      types: templates(n.types),
      moderation: templates(n.moderation),
      reasons: plain(n.reasons),
      tiers: plain(profile.tier),
      pools: plain(pools),
    },
    games: gameNames,
    achievements,
    paths: {
      friends: path("friends/"),
      profileBase: path("u/"),
      play: path("play/"),
      profile: path("profile/"),
      leaderboards: path("leaderboards/"),
      messages: path("messages/"),
      notifications: path("notifications/"),
    },
  };
}

const entry = [
  'export { notificationHref, notificationText } from "./apps/web/src/features/notifications/notification-text.ts";',
  'export { LOCALE_INFO } from "./apps/web/src/i18n/locales.ts";',
  `export const WORDS = ${JSON.stringify(words)};`,
].join("\n");

const banner = [
  "// Generated by scripts/functions-push.mjs (`pnpm functions:push`) from the",
  "// site's notification wording and locale files: do not edit.",
  '// @ts-self-types="./push-words.gen.d.ts"',
].join("\n");

const result = await build({
  stdin: { contents: entry, resolveDir: root, sourcefile: "push-words-entry.js", loader: "js" },
  absWorkingDir: root,
  tsconfig: join(web, "tsconfig.json"),
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  charset: "utf8",
  legalComments: "inline",
  banner: { js: banner },
  write: false,
  logLevel: "warning",
});
const bundle = result.outputFiles[0]?.text ?? "";
writeFileSync(join(out, "push-words.gen.js"), bundle);
writeFileSync(
  join(out, "push-words.gen.d.ts"),
  [
    "// Generated with push-words.gen.js: do not edit. Used by push-text.ts.",
    "export interface PushNotification {",
    "  id: number;",
    "  type: string;",
    "  data: Record<string, unknown>;",
    "  at: string;",
    "  from: { id: string; nickname: string } | null;",
    "}",
    "export interface LocaleWords {",
    "  strings: unknown;",
    "  games: Record<string, string>;",
    "  achievements: Record<string, string>;",
    "  paths: Record<",
    '    "friends" | "profileBase" | "play" | "profile" | "leaderboards" | "messages" | "notifications",',
    "    string",
    "  >;",
    "}",
    "export declare const WORDS: Readonly<Record<string, LocaleWords>>;",
    'export declare const LOCALE_INFO: Readonly<Record<string, { bcp47: string; dir: "ltr" | "rtl" }>>;',
    "export declare function notificationText(",
    "  n: PushNotification,",
    "  s: unknown,",
    "  c: { games: Record<string, string>; achievements: Record<string, string>; locale: string; bcp47: string },",
    "): string | null;",
    'export declare function notificationHref(n: PushNotification, p: LocaleWords["paths"]): string | null;',
    "",
  ].join("\n"),
);
console.log(
  `push-words.gen.js: ${locales.join(", ")} (${String(Math.round(bundle.length / 1024))} KB)`,
);
