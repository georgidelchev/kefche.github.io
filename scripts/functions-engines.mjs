// Server engines: `pnpm functions:engines` (Phase 7, ADR to come in step 13).
// Bundles every game's engine and manifest (packages/games/<id>/engine and
// manifest.ts) into one ES module for the Edge Functions,
// supabase/functions/_shared/engines.gen.js, so the server replays a game with
// the code the browser ran. Deno can't load the sources themselves: they import
// without file extensions. CI rebuilds the bundle and fails on any difference.
//
// `--fixtures` also rewrites _shared/engines.fixtures.json: one seeded game of
// each, played here in Node on the bundle, with its result and a hash of its
// final state. The Deno tests (_shared/engines.test.ts) replay them and must
// agree. A new game needs a fixture policy below.
import { createHash } from "node:crypto";
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
const out = join(root, "supabase/functions/_shared");
const ids = readdirSync(join(root, "packages/games"), { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const entry = [
  ...ids.flatMap((id, i) => [
    `import { engine as e${String(i)} } from "./packages/games/${id}/engine/index.ts";`,
    `import { manifest as m${String(i)} } from "./packages/games/${id}/manifest.ts";`,
  ]),
  'export { canonicalJson } from "./packages/game-sdk/src/engines.ts";',
  'export { RACE_LOG_LIMITS, unpackActions } from "./packages/game-sdk/src/race-log.ts";',
  "export const GAMES = {",
  ...ids.map(
    (id, i) => `  ${JSON.stringify(id)}: { manifest: m${String(i)}, engine: e${String(i)} },`,
  ),
  "};",
].join("\n");

const banner = [
  "// Generated by scripts/functions-engines.mjs (`pnpm functions:engines`) from",
  "// packages/games: do not edit. Typed in engines.ts.",
  '// @ts-self-types="./engines.gen.d.ts"',
].join("\n");

const result = await build({
  stdin: { contents: entry, resolveDir: root, sourcefile: "engines-entry.js", loader: "js" },
  absWorkingDir: root,
  bundle: true,
  format: "esm",
  platform: "neutral",
  mainFields: ["module", "main"],
  target: "es2022",
  legalComments: "inline",
  banner: { js: banner },
  write: false,
  logLevel: "warning",
});
const bundle = result.outputFiles[0]?.text ?? "";
writeFileSync(join(out, "engines.gen.js"), bundle);
writeFileSync(
  join(out, "engines.gen.d.ts"),
  [
    "// Generated with engines.gen.js: do not edit. Typed in engines.ts.",
    "export declare const GAMES: Readonly<Record<string, { manifest: unknown; engine: unknown }>>;",
    "export declare function canonicalJson(value: unknown): string;",
    "export declare const RACE_LOG_LIMITS: { readonly dict: number; readonly runs: number };",
    "export declare function unpackActions(",
    "  log: { dict: unknown[]; runs: string },",
    "  maxActions?: number,",
    "): unknown[] | null;",
    "",
  ].join("\n"),
);
console.log(`engines.gen.js: ${ids.join(", ")} (${String(Math.round(bundle.length / 1024))} KB)`);

if (process.argv.includes("--fixtures")) {
  const { GAMES, canonicalJson } = await import(
    `${pathToFileURL(join(out, "engines.gen.js")).href}?t=${String(Date.now())}`
  );

  /** Small seeded PRNG (mulberry32). */
  const rng = (seed) => {
    let a =
      [...seed].reduce((h, ch) => Math.imul(h ^ ch.charCodeAt(0), 2654435761), 2166136261) >>> 0;
    return () => {
      a = (a + 0x6d2b79f5) >>> 0;
      let t = a;
      t = Math.imul(t ^ (t >>> 15), t | 1);
      t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  };
  const pick = (random, list) => list[Math.floor(random() * list.length)];
  const DIRECTIONS = ["up", "down", "left", "right"];

  /** Race games: the config and the next action of a plausible player. */
  const racePolicies = {
    2048: {
      config: undefined,
      next: (_state, random) => ({ type: "move", direction: pick(random, DIRECTIONS) }),
    },
    // Heads for the food on the 20 × 20 board, never into its own body;
    // without walls, so the edges wrap.
    snake: {
      config: { speed: "normal", walls: false },
      next: (state, random) => {
        const [head = 0] = state.snake;
        const step = (direction) => {
          const row = Math.floor(head / 20) + { up: -1, down: 1, left: 0, right: 0 }[direction];
          const col = (head % 20) + { up: 0, down: 0, left: -1, right: 1 }[direction];
          return ((row + 20) % 20) * 20 + ((col + 20) % 20);
        };
        const back = { up: "down", down: "up", left: "right", right: "left" }[state.direction];
        const safe = DIRECTIONS.filter(
          (d) => d !== back && !state.snake.slice(0, -1).includes(step(d)),
        );
        const dRow = Math.floor(state.food / 20) - Math.floor(head / 20);
        const dCol = (state.food % 20) - (head % 20);
        const toward = [
          dRow < 0 ? "up" : dRow > 0 ? "down" : null,
          dCol < 0 ? "left" : dCol > 0 ? "right" : null,
        ];
        const choice =
          toward.find((d) => d !== null && safe.includes(d)) ??
          (safe.includes(state.direction)
            ? state.direction
            : pick(random, safe.length > 0 ? safe : DIRECTIONS));
        return state.queue.length === 0 && choice !== state.direction
          ? { type: "turn", direction: choice }
          : { type: "tick" };
      },
    },
    sudoku: {
      config: { difficulty: "easy" },
      // A wrong digit now and then, corrected by the next action.
      next: (state, random) => {
        const cell = state.values.findIndex((v, c) => v !== state.solution[c]);
        const right = state.solution[cell];
        const digit = random() < 0.1 ? (right % 9) + 1 : right;
        return { type: "enter", cell, digit };
      },
    },
  };
  /** Turn games: their config (a random legal move each turn, two seats). */
  const turnConfigs = {
    chess: { takebacks: false },
    "dots-and-boxes": undefined,
    "four-in-a-row": undefined,
    reversi: undefined,
  };
  const MAX_ACTIONS = 400;
  const hash = (state) => createHash("sha256").update(canonicalJson(state)).digest("hex");

  const fixtures = ids.map((id) => {
    const { manifest, engine } = GAMES[id];
    const seed = `fixture-${id}`;
    const random = rng(seed);
    if (manifest.kind === "race") {
      const policy = racePolicies[id];
      if (!policy) throw new Error(`Add a fixture policy for the race game "${id}".`);
      let state = engine.initialState(policy.config, seed);
      const actions = [];
      while (actions.length < MAX_ACTIONS && engine.result(state) === null) {
        const action = policy.next(state, random);
        actions.push(action);
        state = engine.apply(state, action);
      }
      return {
        id,
        version: manifest.version,
        config: policy.config ?? null,
        seed,
        actions,
        expected: {
          result: engine.result(state),
          score: engine.score?.(state) ?? null,
          progress: engine.progress(state),
          state: hash(state),
        },
      };
    }
    if (!(id in turnConfigs)) throw new Error(`Add a fixture config for the turn game "${id}".`);
    const config = turnConfigs[id];
    const seats = 2;
    let state = engine.initialState(config, seats, seed);
    const moves = [];
    while (moves.length < MAX_ACTIONS && engine.result(state) === null) {
      const seat = engine.currentSeats(state)[0];
      const action = pick(random, engine.legalActions(state, seat));
      moves.push({ seat, action });
      state = engine.applyAction(state, seat, action);
    }
    // A game the moves didn't finish ends with the side to move resigning, where it can.
    if (engine.result(state) === null) {
      const seat = engine.currentSeats(state)[0];
      const resign = (engine.sideActions?.(state, seat) ?? []).find((a) => a.type === "resign");
      if (resign) {
        moves.push({ seat, action: resign });
        state = engine.applyAction(state, seat, resign);
      }
    }
    return {
      id,
      version: manifest.version,
      config: config ?? null,
      seats,
      seed,
      moves,
      expected: { result: engine.result(state), state: hash(state) },
    };
  });
  writeFileSync(join(out, "engines.fixtures.json"), `${JSON.stringify(fixtures)}\n`);
  console.log(
    `engines.fixtures.json: ${fixtures.map((f) => `${f.id} ${String((f.actions ?? f.moves).length)}`).join(", ")}`,
  );
}
