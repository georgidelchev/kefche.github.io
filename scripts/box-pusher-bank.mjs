// Box Pusher's fixed levels: `node scripts/box-pusher-bank.mjs` writes
// packages/games/box-pusher/engine/bank.gen.ts. Each difficulty gets the 20
// hardest of 40 levels from engine/level.ts (bigger rooms and more boxes than
// a fresh level, searched further: too slow to make while someone waits),
// sorted from fewest pushes to most so the list climbs. The bank is
// committed, and its levels never change once released: players' best
// moves are kept per level.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
const out = join(root, "packages/games/box-pusher/engine/bank.gen.ts");
const SPECS = {
  easy: { inner: 6, boxes: 2, walls: 0.25, minPushes: 999, rooms: 150, budget: 100_000 },
  medium: { inner: 7, boxes: 3, walls: 0.3, minPushes: 999, rooms: 150, budget: 300_000 },
  hard: { inner: 8, boxes: 4, walls: 0.3, minPushes: 999, rooms: 150, budget: 1_000_000 },
};

const bundle = await build({
  entryPoints: [join(root, "packages/games/box-pusher/engine/level.ts")],
  bundle: true,
  format: "esm",
  platform: "neutral",
  write: false,
  logLevel: "warning",
});
const tmp = join(root, "node_modules/.box-pusher-level.mjs");
writeFileSync(tmp, bundle.outputFiles[0]?.text ?? "");
const { makeLevel, toText } = await import(`${pathToFileURL(tmp).href}?t=${String(Date.now())}`);

const bank = {};
for (const [difficulty, spec] of Object.entries(SPECS)) {
  const seen = new Set();
  const found = [];
  for (let i = 0; found.length < 40 && i < 120; i++) {
    const started = Date.now();
    const level = makeLevel(`bank-${difficulty}-${String(i)}`, spec);
    const text = toText(level);
    if (seen.has(text)) continue;
    seen.add(text);
    found.push([text, level.pushes]);
    console.log(
      `${difficulty}: ${String(found.length)}/40, ${String(level.pushes)} pushes (${String(Date.now() - started)} ms)`,
    );
  }
  bank[difficulty] = found
    .sort((a, b) => b[1] - a[1])
    .slice(0, 20)
    .sort((a, b) => a[1] - b[1]);
}
const body = Object.entries(bank)
  .map(([d, list]) => `  ${d}: [\n${list.map((e) => `    ${JSON.stringify(e)},`).join("\n")}\n  ],`)
  .join("\n");
writeFileSync(
  out,
  `// Generated by scripts/box-pusher-bank.mjs: do not edit. Each level is its\n// text (# wall, . goal, $ box, * box on a goal, @ player, + player on a goal)\n// and its fewest pushes.\nexport const BANK: Readonly<Record<"easy" | "medium" | "hard", readonly (readonly [string, number])[]>> = {\n${body}\n};\n`,
);
console.log(
  `bank.gen.ts: ${Object.entries(bank)
    .map(
      ([d, l]) => `${d} ${String(l.length)} (${String(l[0]?.[1])}–${String(l.at(-1)?.[1])} pushes)`,
    )
    .join(", ")}`,
);
