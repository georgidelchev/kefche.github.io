// Klondike's winnable deals: `node scripts/klondike-bank.mjs` writes
// packages/games/klondike/engine/bank.gen.ts. A depth-first solver plays
// candidate deals with the engine's own rules (foundation moves first, then
// moves that turn a card up, then the waste, then drawing), remembering the
// layouts it has seen, within a budget of steps per deal. Deals it wins go
// in the bank, per draw mode. The bank is committed and never changes once
// released (a winnable game names its deal by the seed).
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
const out = join(root, "packages/games/klondike/engine/bank.gen.ts");
const WANT = 120;
const BUDGET = 60_000;

const bundle = await build({
  entryPoints: [join(root, "packages/games/klondike/engine/index.ts")],
  bundle: true,
  format: "esm",
  platform: "neutral",
  write: false,
  logLevel: "warning",
});
const tmp = join(root, "node_modules/.klondike-engine.mjs");
writeFileSync(tmp, bundle.outputFiles[0]?.text ?? "");
const { engine, canMove } = await import(`${pathToFileURL(tmp).href}?t=${String(Date.now())}`);

const key = (s) =>
  [
    s.columns.map((c) => `${c.down.length}:${c.up.join(".")}`).join("|"),
    s.waste.join("."),
    s.stock.length,
    s.foundations.map((f) => f.length).join("."),
  ].join("/");

function movesOf(s) {
  const out = [];
  const piles = [{ waste: true }, ...s.columns.map((_, i) => ({ column: i }))];
  // To the foundations.
  for (const from of piles)
    for (let f = 0; f < 4; f++)
      if (canMove(s, from, { foundation: f }, 1))
        out.push({ from, to: { foundation: f }, count: 1, p: 0 });
  // Column runs that turn a card up or empty a column for a king.
  for (let i = 0; i < 7; i++) {
    const col = s.columns[i];
    for (let count = col.up.length; count >= 1; count--) {
      for (let j = 0; j < 7; j++) {
        if (!canMove(s, { column: i }, { column: j }, count)) continue;
        const whole = count === col.up.length;
        // A king already at the bottom of an empty column stays put.
        if (whole && col.down.length === 0 && s.columns[j].up.length === 0) continue;
        if (!whole) {
          // Part of a run: only to free a card for the foundations.
          const under = col.up[col.up.length - count - 1];
          if (
            under === undefined ||
            ![0, 1, 2, 3].some((f) =>
              canMove(
                {
                  ...s,
                  columns: s.columns.map((c, k) =>
                    k === i ? { ...c, up: c.up.slice(0, -count) } : c,
                  ),
                },
                { column: i },
                { foundation: f },
                1,
              ),
            )
          )
            continue;
        }
        out.push({
          from: { column: i },
          to: { column: j },
          count,
          p: whole && col.down.length > 0 ? 1 : 3,
        });
      }
    }
  }
  for (let j = 0; j < 7; j++)
    if (canMove(s, { waste: true }, { column: j }, 1))
      out.push({ from: { waste: true }, to: { column: j }, count: 1, p: 2 });
  out.sort((a, b) => a.p - b.p);
  return out;
}

function solve(state) {
  const seen = new Set();
  let steps = 0;
  const stack = [state];
  while (stack.length > 0 && steps < BUDGET) {
    const s = stack.pop();
    steps++;
    if (engine.result(s)) return true;
    const k = key(s);
    if (seen.has(k)) continue;
    seen.add(k);
    const next = [];
    for (const m of movesOf(s))
      next.push(
        engine.apply({ ...s, history: [] }, { move: { from: m.from, to: m.to, count: m.count } }),
      );
    const drawn = engine.apply({ ...s, history: [] }, { draw: true });
    // Push the least wanted first: the stack pops the best next.
    if (drawn !== s) stack.push(drawn);
    for (let i = next.length - 1; i >= 0; i--) stack.push(next[i]);
  }
  return false;
}

const bank = {};
for (const draw of [1, 3]) {
  const found = [];
  let tried = 0;
  for (let i = 0; found.length < WANT && i < WANT * 6; i++) {
    tried++;
    const candidate = `bank${String(draw)}-${String(i)}`;
    const state = engine.initialState({ draw, deal: "random" }, candidate);
    if (solve(state)) found.push(`klondike:${candidate}`);
  }
  bank[draw] = found;
  console.log(`draw ${String(draw)}: ${String(found.length)} winnable of ${String(tried)} tried`);
}
writeFileSync(
  out,
  `// Generated by scripts/klondike-bank.mjs: do not edit. Deals the solver won, by draw mode.\nexport const WINNABLE: Readonly<Record<1 | 3, readonly string[]>> = ${JSON.stringify(bank)};\n`,
);
console.log(`wrote ${out}`);
